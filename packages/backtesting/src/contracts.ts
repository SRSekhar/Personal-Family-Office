import type { BarInterval, PriceAdjustmentBasis } from '@pfo/market-data';
import type { InstrumentReference } from '@pfo/market-data';
import type { Currency } from '@pfo/models';

export type IsoTimestamp = string;
export type BacktestSourceKind = 'provider' | 'exchange' | 'issuer' | 'user-supplied' | 'other';
export type BacktestLicenseStatus = 'reviewed' | 'unreviewed' | 'restricted';
export type BacktestPointInTimeStatus = 'per-observation' | 'snapshot-only' | 'not-guaranteed' | 'unknown';

export interface BacktestDatasetSource {
    readonly kind: BacktestSourceKind;
    readonly name: string;
    readonly url?: string;
    readonly licenseName: string;
    readonly licenseStatus: BacktestLicenseStatus;
    readonly termsUrl?: string;
    readonly attributionText: string;
    readonly retrievedAt: IsoTimestamp;
    readonly contentDigest: string;
    readonly licenseReviewedAt?: IsoTimestamp;
    readonly pointInTimeStatus: BacktestPointInTimeStatus;
    readonly pointInTimeLimitation?: string;
}

export interface BacktestBarObservation {
    readonly instrumentId: string;
    readonly providerInstrumentId?: string;
    readonly interval: BarInterval;
    readonly startAt: IsoTimestamp;
    readonly endAt: IsoTimestamp;
    readonly open: number;
    readonly high: number;
    readonly low: number;
    readonly close: number;
    readonly currency: Currency;
    readonly volume?: number;
    readonly adjustmentBasis: PriceAdjustmentBasis;
    readonly marketTimeZone: string;
    /** When this exact observation/value was available to market participants. Never inferred. */
    readonly availableAt?: IsoTimestamp;
    /** When this immutable observation was imported/recorded in PFO. */
    readonly recordedAt: IsoTimestamp;
}

export interface BacktestDataset {
    readonly id: string;
    readonly version: number;
    readonly instrument: InstrumentReference;
    readonly interval: BarInterval;
    readonly adjustmentBasis: PriceAdjustmentBasis;
    readonly marketTimeZone: string;
    readonly source: BacktestDatasetSource;
    readonly contentDigest: string;
    readonly recordedAt: IsoTimestamp;
    readonly coverage: {
        readonly startAt: IsoTimestamp;
        readonly endAt: IsoTimestamp;
        readonly status: 'complete' | 'partial' | 'unknown';
        /** Explicit expected bar end timestamps from a reviewed calendar; never generated by the importer. */
        readonly expectedBarEndAt: readonly IsoTimestamp[];
    };
    readonly bars: readonly BacktestBarObservation[];
}

export interface BacktestUniverseMembership {
    readonly id: string;
    readonly instrumentId: string;
    readonly status: 'included' | 'excluded';
    readonly effectiveFrom: IsoTimestamp;
    readonly effectiveTo?: IsoTimestamp;
    /** When this membership fact became knowable to market participants. */
    readonly availableAt?: IsoTimestamp;
    /** When PFO recorded this membership fact. */
    readonly recordedAt: IsoTimestamp;
    readonly sourceEvidenceId: string;
}

export interface BacktestUniverse {
    readonly id: string;
    readonly version: number;
    readonly name: string;
    readonly pointInTimeComplete: boolean;
    readonly recordedAt: IsoTimestamp;
    readonly memberships: readonly BacktestUniverseMembership[];
}

export interface BacktestTradingCalendar {
    readonly id: string;
    readonly version: number;
    readonly exchange: string;
    readonly interval: BarInterval;
    readonly marketTimeZone: string;
    readonly sourceName: string;
    readonly sourceEvidenceId: string;
    readonly recordedAt: IsoTimestamp;
    readonly coverage: {
        readonly startAt: IsoTimestamp;
        readonly endAt: IsoTimestamp;
        /** Explicit ordered schedule. No weekday or holiday inference is permitted. */
        readonly expectedBarEndAt: readonly IsoTimestamp[];
    };
}

export interface BacktestStrategyDescriptor {
    readonly id: string;
    readonly version: string;
    readonly implementationDigest: string;
    readonly parametersDigest: string;
    readonly supportedIntervals: readonly BarInterval[];
}

export interface BacktestCostModelDescriptor {
    readonly id: string;
    readonly version: string;
    readonly currency: Currency;
    readonly implementationDigest: string;
    readonly parametersDigest: string;
}

export interface BacktestExecutionPolicy {
    readonly signalTiming: 'bar-close';
    readonly fillTiming: 'next-bar-open';
    readonly orderType: 'market';
    readonly slippageBasisPoints: number;
    readonly maxVolumeParticipation: number;
    readonly missingVolumePolicy: 'reject-order';
    readonly insufficientVolumePolicy: 'partial-fill' | 'reject-order';
    readonly unfilledRemainderPolicy: 'expire';
}

export interface BacktestRunConfiguration {
    readonly id: string;
    readonly startAt: IsoTimestamp;
    readonly endAt: IsoTimestamp;
    /** Local PFO knowledge-state cutoff for selecting recorded datasets and revisions. */
    readonly recordedAtCutoff: IsoTimestamp;
    readonly currency: Currency;
    readonly initialCapital: {
        readonly amount: number;
        readonly currency: Currency;
    };
    readonly datasetIds: readonly string[];
    readonly universeId: string;
    readonly universeVersion: number;
    readonly universeSelection: 'point-in-time' | 'static-exploratory';
    readonly survivorshipBiasAcknowledged: boolean;
    readonly calendarId: string;
    readonly calendarVersion: number;
    readonly strategy: BacktestStrategyDescriptor;
    readonly execution: BacktestExecutionPolicy;
    readonly costModel: BacktestCostModelDescriptor;
    readonly pointInTimeRequired: boolean;
    readonly corporateActionPolicy: 'require-complete-events' | 'exclude-affected-periods' | 'reject-any-action';
}

export interface BacktestRunValidationContext {
    readonly datasets: readonly BacktestDataset[];
    readonly universe: BacktestUniverse;
    readonly calendar: BacktestTradingCalendar;
}
